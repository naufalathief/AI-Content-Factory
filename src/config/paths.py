"""
Path configuration module.

This module centralizes all project directories used throughout the
FER Transfer Learning Framework. Every module should access filesystem
locations through this module instead of using hardcoded paths.

Author:
    Naufal Muhammad Athif

Created:
    July 2026
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

_PROJECT_ROOT_LEVEL = 2


@dataclass(frozen=True, slots=True)
class PathSettings:
    """
    Centralized project path configuration.

    All project directories are resolved relative to the project root.

    Attributes:
        project_root: Root directory of the project.

        configs_dir: Configuration files directory.

        data_dir: Dataset root directory.
        raw_data_dir: Raw datasets.
        processed_data_dir: Processed datasets.
        cache_dir: Cache directory.
        external_data_dir: External datasets.

        docs_dir: Documentation directory.
        notebooks_dir: Jupyter notebooks.

        outputs_dir: Experiment outputs.
        checkpoints_dir: Model checkpoints.
        logs_dir: Training logs.
        predictions_dir: Prediction outputs.
        reports_dir: Reports directory.
        figures_dir: Report figures.
        metrics_dir: Evaluation metrics.
        tables_dir: Generated tables.

        src_dir: Source code.
        tests_dir: Unit tests.
    """

    project_root: Path = field(
        default_factory=lambda: Path(__file__).resolve().parents[_PROJECT_ROOT_LEVEL]
    )

    configs_dir: Path = field(init=False)

    data_dir: Path = field(init=False)
    raw_data_dir: Path = field(init=False)
    processed_data_dir: Path = field(init=False)
    cache_dir: Path = field(init=False)
    external_data_dir: Path = field(init=False)

    docs_dir: Path = field(init=False)
    notebooks_dir: Path = field(init=False)

    outputs_dir: Path = field(init=False)
    checkpoints_dir: Path = field(init=False)
    logs_dir: Path = field(init=False)
    predictions_dir: Path = field(init=False)
    reports_dir: Path = field(init=False)

    figures_dir: Path = field(init=False)
    metrics_dir: Path = field(init=False)
    tables_dir: Path = field(init=False)

    src_dir: Path = field(init=False)
    tests_dir: Path = field(init=False)

    def __post_init__(self) -> None:
        """Initialize all project directories."""

        root = self.project_root

        if not root.exists():
            raise FileNotFoundError(f"Project root directory does not exist: {root}")

        object.__setattr__(self, "configs_dir", root / "configs")

        object.__setattr__(self, "data_dir", root / "data")
        object.__setattr__(self, "raw_data_dir", self.data_dir / "raw")
        object.__setattr__(self, "processed_data_dir", self.data_dir / "processed")
        object.__setattr__(self, "cache_dir", self.data_dir / "cache")
        object.__setattr__(self, "external_data_dir", self.data_dir / "external")

        object.__setattr__(self, "docs_dir", root / "docs")
        object.__setattr__(self, "notebooks_dir", root / "notebooks")

        object.__setattr__(self, "outputs_dir", root / "outputs")
        object.__setattr__(self, "checkpoints_dir", self.outputs_dir / "checkpoints")
        object.__setattr__(self, "logs_dir", self.outputs_dir / "logs")
        object.__setattr__(self, "predictions_dir", self.outputs_dir / "predictions")
        object.__setattr__(self, "reports_dir", self.outputs_dir / "reports")

        object.__setattr__(self, "figures_dir", self.reports_dir / "figures")
        object.__setattr__(self, "metrics_dir", self.reports_dir / "metrics")
        object.__setattr__(self, "tables_dir", self.reports_dir / "tables")

        object.__setattr__(self, "src_dir", root / "src")
        object.__setattr__(self, "tests_dir", root / "tests")

    def create_directories(self) -> None:
        """
        Create project output directories if they do not already exist.

        Notes:
            This method intentionally creates only directories that are
            generated by the framework during execution.

            Dataset directories are excluded because datasets must be
            provided by the user.
        """

        directories = (
            self.outputs_dir,
            self.checkpoints_dir,
            self.logs_dir,
            self.predictions_dir,
            self.reports_dir,
            self.figures_dir,
            self.metrics_dir,
            self.tables_dir,
        )

        for directory in directories:
            directory.mkdir(parents=True, exist_ok=True)


paths = PathSettings()
